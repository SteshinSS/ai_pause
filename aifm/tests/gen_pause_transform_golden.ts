// Generates the cross-language golden fixture for the pause (freeze + reduce)
// transform. Runs the REAL frontend applyPause (from utils/pauseTransform.ts)
// over a set of cases and writes both the base series and the outputs to
// tests/golden_data/pause_transform_golden.json.
//
// The Python test (tests/test_pause_transform.py) reads this file, feeds the
// same base series through progress_model.pause_transform.freeze_and_reduce_time_series,
// and asserts the outputs match. This pins the two implementations together
// without reimplementing the transform in either test.
//
// Regenerate (only with explicit permission, since it is golden data):
//   node tests/gen_pause_transform_golden.ts
//
// Run from the repo root.

import { writeFileSync } from 'node:fs';
import { applyPause, type InputTimeSeries } from '../utils/pauseTransform.ts';

// A small but representative base series. All four channels are raw
// (exponentially growing) quantities — training_H100e is raw H100e like the
// others since the continuous-training port. Values are positive everywhere so
// expInterp uses its exponential branch.
const base: InputTimeSeries = {
  time:             [2025.0, 2026.0, 2027.0, 2028.0, 2029.0, 2030.0],
  L_HUMAN:          [1.0e5, 1.5e5, 2.3e5, 3.4e5, 5.1e5, 7.6e5],
  inference_H100e:  [2.0e6, 6.0e6, 1.8e7, 5.4e7, 1.6e8, 4.9e8],
  experiment_H100e: [3.0e6, 7.5e6, 1.9e7, 4.7e7, 1.2e8, 2.9e8],
  training_H100e:   [1.0e5, 4.0e5, 1.6e6, 6.3e6, 2.5e7, 1.0e8],
};

interface Reductions {
  experiment: number;
  inference: number;
  labor: number;
  training: number;
}

const cases: Array<{ name: string; pause_year: number; reductions: Reductions }> = [
  // Pure freeze (all reductions 1.0), pause strictly between grid points.
  { name: 'freeze_only_fractional', pause_year: 2027.4, reductions: { experiment: 1, inference: 1, labor: 1, training: 1 } },
  // Pure freeze, pause exactly on a grid point (no insert path).
  { name: 'freeze_only_on_gridpoint', pause_year: 2028.0, reductions: { experiment: 1, inference: 1, labor: 1, training: 1 } },
  // Symmetric 10x reduction on all four channels, fractional pause (the experiment's main case).
  { name: 'reduce_10x_all_fractional', pause_year: 2027.4, reductions: { experiment: 10, inference: 10, labor: 10, training: 10 } },
  // Symmetric 10x reduction on all four channels, pause on a grid point.
  { name: 'reduce_10x_all_gridpoint', pause_year: 2028.0, reductions: { experiment: 10, inference: 10, labor: 10, training: 10 } },
  // Asymmetric reductions, fractional pause.
  { name: 'reduce_asymmetric_fractional', pause_year: 2026.5, reductions: { experiment: 2, inference: 4, labor: 1, training: 10 } },
  // Pause near the start (between first two points).
  { name: 'reduce_10x_early', pause_year: 2025.25, reductions: { experiment: 10, inference: 10, labor: 10, training: 10 } },
];

const out = {
  _comment: 'Golden fixture for the pause transform. Generated by tests/gen_pause_transform_golden.ts running the real applyPause. Do not hand-edit.',
  base,
  cases: cases.map((c) => ({
    name: c.name,
    pause_year: c.pause_year,
    reductions: c.reductions,
    output: applyPause(
      base,
      c.pause_year,
      c.reductions.experiment,
      c.reductions.inference,
      c.reductions.labor,
      c.reductions.training,
    ),
  })),
};

const path = new URL('./golden_data/pause_transform_golden.json', import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + '\n');
console.log(`Wrote ${out.cases.length} cases to ${path.pathname}`);
